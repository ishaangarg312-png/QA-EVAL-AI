import io
from datetime import datetime, timezone
from typing import List, Dict, Any, Optional
import openpyxl
from openpyxl.styles import Font, PatternFill, Alignment, Border, Side
from openpyxl.utils import get_column_letter

from app.schemas.generator_schemas import ColumnConfig, EntityLevel

class TestGeneratorExcelBuilder:
    """
    Production-grade openpyxl Excel spreadsheet builder supporting N-level recursive
    entity hierarchies, dynamic column layouts, and multi-level cell merging.
    """

    HEADER_FILL = PatternFill(start_color="1E293B", end_color="1E293B", fill_type="solid")  # Slate 800
    HEADER_FONT = Font(name="Segoe UI", size=11, bold=True, color="FFFFFF")

    TITLE_FILL = PatternFill(start_color="0F172A", end_color="0F172A", fill_type="solid")   # Slate 900
    TITLE_FONT = Font(name="Segoe UI", size=14, bold=True, color="FFFFFF")

    META_FILL = PatternFill(start_color="F1F5F9", end_color="F1F5F9", fill_type="solid")    # Slate 100
    META_FONT = Font(name="Segoe UI", size=9, bold=False, color="475569")

    ZEBRA_FILL_A = PatternFill(start_color="FFFFFF", end_color="FFFFFF", fill_type="solid")
    ZEBRA_FILL_B = PatternFill(start_color="F8FAFC", end_color="F8FAFC", fill_type="solid")  # Ultra soft slate

    DATA_FONT = Font(name="Segoe UI", size=10, color="0F172A")
    BOLD_DATA_FONT = Font(name="Segoe UI", size=10, bold=True, color="0F172A")

    THIN_BORDER_SIDE = Side(style="thin", color="CBD5E1")
    BORDER_ALL = Border(
        left=THIN_BORDER_SIDE,
        right=THIN_BORDER_SIDE,
        top=THIN_BORDER_SIDE,
        bottom=THIN_BORDER_SIDE,
    )

    @classmethod
    def get_leaf_count(cls, item: Dict[str, Any]) -> int:
        """
        Recursively calculates the number of spreadsheet rows consumed by a tree node.
        """
        children = item.get("children") or item.get("data_rows") or []
        # Check alternative friendly child keys
        if not children:
            for k in ("test_cases", "test_data", "data", "followups", "followup_prompts", "turns", "assertions", "items"):
                if k in item and isinstance(item[k], list) and len(item[k]) > 0:
                    children = item[k]
                    break

        if not children:
            return 1
        return sum(cls.get_leaf_count(c) for c in children)

    @classmethod
    def generate_excel(
        cls,
        columns: List[ColumnConfig],
        data: List[Dict[str, Any]],
        entity_levels: Optional[List[EntityLevel]] = None,
        mode: str = "both",
        title: str = "AI Test Suite & Test Data Matrix",
        sheet_name: str = "Test Matrix"
    ) -> io.BytesIO:
        """
        Builds the complete formatted Excel workbook supporting recursive N-level merging.
        """
        wb = openpyxl.Workbook()
        ws = wb.active
        ws.title = sheet_name[:31]
        ws.views.sheetView[0].showGridLines = True

        total_cols = max(len(columns), 1)

        # -------------------------------------------------------------
        # 1. Top Title & Summary Metadata Banner
        # -------------------------------------------------------------
        ws.row_dimensions[1].height = 36
        ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=total_cols)
        top_cell = ws.cell(row=1, column=1, value=f"  {title.upper()}")
        top_cell.font = cls.TITLE_FONT
        top_cell.fill = cls.TITLE_FILL
        top_cell.alignment = Alignment(horizontal="left", vertical="center")

        for col_idx in range(1, total_cols + 1):
            cell = ws.cell(row=1, column=col_idx)
            cell.fill = cls.TITLE_FILL
            cell.border = cls.BORDER_ALL

        now_str = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
        total_leaf_rows = sum(cls.get_leaf_count(item) for item in data)
        meta_text = f"  Generated by EVAL AI  |  Top Entities: {len(data)}  |  Total Leaf Rows: {total_leaf_rows}  |  Columns: {len(columns)}  |  Generated At: {now_str}"

        ws.row_dimensions[2].height = 22
        ws.merge_cells(start_row=2, start_column=1, end_row=2, end_column=total_cols)
        meta_cell = ws.cell(row=2, column=1, value=meta_text)
        meta_cell.font = cls.META_FONT
        meta_cell.fill = cls.META_FILL
        meta_cell.alignment = Alignment(horizontal="left", vertical="center")
        for col_idx in range(1, total_cols + 1):
            cell = ws.cell(row=2, column=col_idx)
            cell.fill = cls.META_FILL
            cell.border = cls.BORDER_ALL

        # Spacer row
        ws.row_dimensions[3].height = 10

        # -------------------------------------------------------------
        # 2. Table Header Row (Row 4)
        # -------------------------------------------------------------
        header_row = 4
        ws.row_dimensions[header_row].height = 28
        for col_idx, col in enumerate(columns, start=1):
            cell = ws.cell(row=header_row, column=col_idx, value=col.name)
            cell.font = cls.HEADER_FONT
            cell.fill = cls.HEADER_FILL
            cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
            cell.border = cls.BORDER_ALL

        # -------------------------------------------------------------
        # 3. Recursive N-Level Data Population & Cell Merging
        # -------------------------------------------------------------
        current_row = 5

        def render_node(item: Dict[str, Any], start_r: int, zebra_fill: PatternFill) -> int:
            leaf_span = cls.get_leaf_count(item)
            end_r = start_r + leaf_span - 1

            # Format borders & zebra fill across all cells in [start_r, end_r]
            for r in range(start_r, end_r + 1):
                ws.row_dimensions[r].height = 24
                for c in range(1, total_cols + 1):
                    cell = ws.cell(row=r, column=c)
                    cell.border = cls.BORDER_ALL
                    cell.fill = zebra_fill
                    cell.alignment = Alignment(horizontal="left", vertical="center", wrap_text=True)

            # Node fields could be in 'fields', 'case_fields', or direct keys
            fields = item.get("fields") or item.get("case_fields") or item

            # Write values for any columns present on this node
            for col_idx, col in enumerate(columns, start=1):
                val = fields.get(col.name)
                if val is None:
                    val = fields.get(col.id)

                if val is not None and str(val).strip() != "":
                    cell = ws.cell(row=start_r, column=col_idx, value=str(val).strip())
                    is_id = "id" in col.name.lower() or "code" in col.name.lower()
                    cell.font = cls.BOLD_DATA_FONT if is_id else cls.DATA_FONT

                    # If merge_rows is enabled for this column and leaf_span > 1, merge vertically
                    if col.merge_rows and leaf_span > 1:
                        ws.merge_cells(
                            start_row=start_r,
                            start_column=col_idx,
                            end_row=end_r,
                            end_column=col_idx
                        )
                        cell.alignment = Alignment(
                            horizontal="center" if is_id else "left",
                            vertical="center",
                            wrap_text=True
                        )

            # Recurse for child nodes
            children = item.get("children") or item.get("data_rows") or []
            if not children:
                for k in ("test_cases", "test_data", "data", "followups", "followup_prompts", "turns", "assertions", "items"):
                    if k in item and isinstance(item[k], list) and len(item[k]) > 0:
                        children = item[k]
                        break

            if children:
                child_curr_r = start_r
                for child in children:
                    c_span = render_node(child, child_curr_r, zebra_fill)
                    child_curr_r += c_span

            return leaf_span

        # Render each top-level entity
        for root_idx, root_item in enumerate(data):
            z_fill = cls.ZEBRA_FILL_B if root_idx % 2 == 1 else cls.ZEBRA_FILL_A
            span = render_node(root_item, current_row, z_fill)
            current_row += span

        # -------------------------------------------------------------
        # 4. Auto Column Width Calculation
        # -------------------------------------------------------------
        for col_idx, col in enumerate(columns, start=1):
            col_letter = get_column_letter(col_idx)
            header_len = len(str(col.name))
            max_len = header_len

            for r in range(header_row + 1, min(current_row, header_row + 50)):
                cell_val = ws.cell(row=r, column=col_idx).value
                if cell_val:
                    lines = str(cell_val).split("\n")
                    for l in lines:
                        max_len = max(max_len, min(len(l), 50))

            target_width = max(14, min(max_len + 4, 52))
            ws.column_dimensions[col_letter].width = target_width

        output = io.BytesIO()
        wb.save(output)
        output.seek(0)
        return output
